def get_month_number(value):

    if pd.isna(value):
        return np.nan

    value = str(value).strip().lower()

    # Hilangkan titik
    value = value.replace(".", " ")

    # Rapikan spasi
    value = " ".join(value.split())

    for key, number in month_map.items():

        if key in value:
            return number

    return np.nan

