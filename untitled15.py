# MEMPERBAIKI PENULISAN ANGKA PADA KOLOM NUMERIK

def clean_number(value):

    if pd.isna(value):
        return np.nan

    if isinstance(value, (int, float, np.integer, np.floating)):
        return float(value)

    value = str(value).strip()

    if value in ["", "-", "–", "—", "nan", "None"]:
        return np.nan

    value = value.replace("%", "")
    value = value.replace(" ", "")

    # Contoh:
    # 1.234.567,89 -> 1234567.89
    if "," in value and "." in value:

        if value.rfind(",") > value.rfind("."):
            value = value.replace(".", "")
            value = value.replace(",", ".")
        else:
            value = value.replace(",", "")

    # Contoh:
    # 1,234,567
    # atau
    # 123,45
    elif "," in value:

        parts = value.split(",")

        if len(parts[-1]) <= 2:
            value = value.replace(",", ".")
        else:
            value = value.replace(",", "")

    # Contoh:
    # 1.234.567
    elif value.count(".") > 1:
        value = value.replace(".", "")

    try:
        return float(value)

    except:
        return np.nan

